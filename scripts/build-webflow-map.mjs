#!/usr/bin/env node
/**
 * Webflow image → repo copies (media/webflow-assets.json, read by src/core/media-index.js)
 * ----------------------------------------------------------------------------------------
 * CMS images sit on Webflow's CDN at full size only (it makes no smaller versions of these WebPs), so every
 * homepage tile would download its 2048 px image just to show a thumbnail, and phones would get the 2048 px file
 * in the project view. The media pipeline already built a 480 px (sm) and 1280 px (md) copy of each one; this
 * finds them.
 *
 * Every CMS image on the live Home + About pages (and any URLs passed in) is downloaded once — cached by URL in
 * media/.cache-webflow.json, since Webflow asset URLs never change — hashed, and matched by content to a
 * `-lg.webp` in public/media. So a renamed or renumbered file still matches, and a different picture under the
 * same name doesn't. Images with no match keep the full-size file only.
 *
 *   npm run media:map                       # the CMS images on the live pages
 *   npm run media:map -- <url> [<url> …]    # plus these (e.g. set in the CMS but not published yet)
 *
 * The release script runs it before building, so each release carries a map that matches its own files.
 */
import { createHash } from 'node:crypto';
import { existsSync } from 'node:fs';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'media/webflow-assets.json');
const CACHE = path.join(ROOT, 'media/.cache-webflow.json');
const PAGES = ['https://www.zacharyallott.com/', 'https://www.zacharyallott.com/about'];
const extra = process.argv.slice(2).filter((a) => /^https?:\/\//.test(a));

const sha = (buf) => createHash('sha256').update(buf).digest('hex');
const assetId = (url) => /\/([0-9a-f]{24})_[^/]*$/.exec(new URL(url).pathname)?.[1];

// 1. The repo's images, by the content of their largest (lg) file.
const manifests = [path.join(ROOT, 'public/media/media.json'), path.join(ROOT, 'public/media/about/media.json')];
const projectsDir = path.join(ROOT, 'public/media/projects');
for (const slug of await fs.readdir(projectsDir).catch(() => [])) {
  const m = path.join(projectsDir, slug, 'media.json');
  if (existsSync(m)) manifests.push(m);
}
const byHash = new Map();
for (const file of manifests.filter(existsSync)) {
  for (const item of JSON.parse(await fs.readFile(file, 'utf8')).items) {
    const { sm, md, lg } = item.images ?? {};
    if (item.type !== 'image' || !sm || !md || !lg) continue;
    const prefix = lg.src.replace(/-lg\.webp$/, '');
    if (sm.src !== `${prefix}-sm.webp` || md.src !== `${prefix}-md.webp`) continue;
    const lgFile = path.join(ROOT, 'public', lg.src);
    if (!existsSync(path.join(ROOT, 'public', sm.src)) || !existsSync(path.join(ROOT, 'public', md.src)) || !existsSync(lgFile)) continue;
    byHash.set(sha(await fs.readFile(lgFile)), [prefix, sm.width, sm.height, md.width, md.height, lg.width, lg.height]);
  }
}

// 2. The CMS images: on the live pages (the hidden Projects list carries every Image N), plus any passed in.
const cache = existsSync(CACHE) ? JSON.parse(await fs.readFile(CACHE, 'utf8')) : {};
const urls = new Set(extra);
for (const page of PAGES) {
  try {
    const html = await (await fetch(page)).text();
    for (const tag of html.match(/<img\b[^>]*\bwork-image-\d+[^>]*>/g) ?? []) {
      const src = /\ssrc="([^"]+)"/.exec(tag)?.[1];
      if (src && assetId(src)) urls.add(src);
    }
  } catch (err) {
    console.warn(`! couldn't read ${page}: ${err.message} — using the cache only`);
  }
}
for (const url of Object.keys(cache)) urls.add(url); // keep everything seen before (asset URLs are permanent)

let fetched = 0;
for (const url of urls) {
  if (cache[url]) continue;
  const res = await fetch(url);
  if (!res.ok) {
    console.warn(`! ${res.status} ${url}`);
    continue;
  }
  cache[url] = sha(Buffer.from(await res.arrayBuffer()));
  fetched++;
}
await fs.writeFile(CACHE, JSON.stringify(cache, null, 2));

// 3. Match.
const assets = {};
let unmatched = 0;
for (const url of [...urls].sort()) {
  const hit = cache[url] && byHash.get(cache[url]);
  if (hit) assets[assetId(url)] = hit;
  else if (!/-poster\.webp$/.test(url)) unmatched++; // video posters have no smaller copies; they're small already
}
const doc = {
  _readme: 'Generated by scripts/build-webflow-map.mjs. Webflow asset id → [repo path prefix (+ -sm/-md/-lg.webp), sm w, sm h, md w, md h, lg w, lg h].',
  assets,
};
await fs.writeFile(OUT, `${JSON.stringify(doc)}\n`);
console.log(`Webflow images: ${urls.size} (${fetched} downloaded) → ${Object.keys(assets).length} matched to repo copies, ${unmatched} images without one.`);
